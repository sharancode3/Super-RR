def derive_decision_category(availability_status: str, raw_category: str = "") -> str:
    """Enforce positive evidence discipline prior to 17 Nov 2026 retention lists and 16 Dec auction pool."""
    if raw_category in ("BENCHMARK_ONLY", "INCUMBENT_RETENTION", "UNVERIFIED_HOLD"):
        return raw_category
    avail = str(availability_status).upper()
    if avail == "INCUMBENT_RR":
        return "INCUMBENT_RETENTION"
    if "MISSING" in avail:
        return "UNVERIFIED_HOLD"
    if any(tok in avail for tok in ("UNTOUCHABLE", "BENCHMARK", "RETIRED", "INELIGIBLE")):
        return "BENCHMARK_ONLY"
    if "TRADE_REQUIRED" in avail:
        return "CONDITIONAL_TRADE_OR_RELEASE_WATCH"
    if any(tok in avail for tok in ("FITNESS", "UNVERIFIED", "REGISTRATION", "NOC", "POLICY_CONTINGENT")):
        return "CONDITIONAL_REGISTRATION_FITNESS_WATCH"
    return "CONDITIONAL_RELEASE_WATCH"


def derive_route_tier(availability_status: str) -> str:
    """Classify route verification explicitly as CONFIRMED, CONDITIONAL, or UNVERIFIED."""
    avail = str(availability_status).upper()
    if avail == "INCUMBENT_RR" or any(tok in avail for tok in ("UNTOUCHABLE", "BENCHMARK", "RETIRED", "INELIGIBLE")):
        return "CONFIRMED"
    if any(tok in avail for tok in ("UNVERIFIED", "MISSING")):
        return "UNVERIFIED"
    return "CONDITIONAL"


for _rec in RAW_TRANSACTION_RECORDS:
    _rec.decision_category = derive_decision_category(_rec.availability_status, _rec.decision_category)


def _extract_pack_ipl_history(raw_dir: Optional[Path]) -> pd.DataFrame:
    """Derive 2026 pack team and latest historical IPL team directly from raw pack mapping."""
    candidate_dir = Path(raw_dir) if raw_dir is not None else Path("6af3166e7b922_data_pack")
    map_path = candidate_dir / "competition_team_player_mapping.csv"
    comp_path = candidate_dir / "competitions.csv"
    if not map_path.exists() or not comp_path.exists():
        return pd.DataFrame(columns=["player_id", "pack_2026_franchise", "latest_pack_ipl_season", "latest_pack_ipl_franchise"])

    ctp = pd.read_csv(map_path)
    comp = pd.read_csv(comp_path)
    ipl_comps = comp[comp["comp_name"].astype(str).str.contains("IPL", na=False)][["comp_id", "comp_name", "season"]]
    ipl_ctp = ctp.merge(ipl_comps, on=["comp_id", "comp_name"], how="inner")

    f2026 = (
        ipl_ctp[ipl_ctp["comp_id"].eq(3298)]
        .groupby("player_id")["team_name"]
        .agg(lambda s: " / ".join(sorted(set(s.dropna()))))
        .rename("pack_2026_franchise")
    )
    latest = (
        ipl_ctp.sort_values(["player_id", "season", "comp_id"])
        .groupby("player_id")
        .last()[["season", "team_name"]]
        .rename(columns={"season": "latest_pack_ipl_season", "team_name": "latest_pack_ipl_franchise"})
    )
    return latest.join(f2026, how="outer").reset_index()


def build_ipl_availability_registry(
    output_dir: Optional[Path] = None,
    raw_dir: Optional[Path] = None,
    as_of_date: Optional[str] = "2026-11-13",
) -> pd.DataFrame:
    """Build pack-verified dated IPL squad, trade, and 2027 pre-retention registry as of specified date."""
    pack_hist = _extract_pack_ipl_history(raw_dir).set_index("player_id").to_dict("index")
    rows = []
    for r in RAW_TRANSACTION_RECORDS:
        # Enforce publication date cutoff: ignore records published in the future
        if as_of_date is not None and r.publication_date > as_of_date:
            continue
        p_info = pack_hist.get(r.player_id, {})
        pack_2026 = p_info.get("pack_2026_franchise")
        latest_season = p_info.get("latest_pack_ipl_season")
        latest_fr = p_info.get("latest_pack_ipl_franchise")
        
        # Enforce effective date: if announced but effective in future, hold prior franchise
        if as_of_date is not None and r.effective_date > as_of_date:
            curr_fr = r.verified_source_franchise
            avail_st = "ANNOUNCED_PENDING_EFFECTIVE_DATE"
            dec_cat = "PENDING_EFFECTIVE_DATE"
        else:
            curr_fr = r.current_franchise
            avail_st = r.availability_status
            dec_cat = r.decision_category

        rows.append({
            "player_id": r.player_id,
            "player_name": r.player_name,
            "verified_source_franchise": r.verified_source_franchise,
            "pack_2026_franchise": pack_2026 if pd.notna(pack_2026) else "NONE_IN_2026_PACK",
            "latest_pack_ipl_season": int(latest_season) if pd.notna(latest_season) else None,
            "latest_pack_ipl_franchise": latest_fr if pd.notna(latest_fr) else "NONE_IN_PACK",
            "current_franchise": curr_fr,
            "transaction_type": r.transaction_type,
            "effective_date": r.effective_date,
            "publication_date": r.publication_date,
            "source_season": r.source_season,
            "source_url": r.source_url,
            "availability_status": avail_st,
            "fitness_clearance_status": r.fitness_clearance_status,
            "auction_registration_status": r.auction_registration_status,
            "reported_registration": (
                "INTERNAL_ROSTER_MEMBER" if (r.auction_registration_status == "INTERNAL_SQUAD" or "INCUMBENT" in dec_cat)
                else ("REPORTED_REGISTRATION_BCB_NOV11" if r.auction_registration_status == "REPORTED_REG_PENDING_FINAL_LIST_AND_NOC"
                else "PENDING_NOV23_CUTOFF")
            ),
            "confirmed_auction_entry": (
                "INTERNAL_RR_RETENTION_DECISION" if ("INCUMBENT" in dec_cat or r.transaction_type == "INCUMBENT_RR_SQUAD")
                else ("CONDITIONAL_ON_BCCI_NOC_CLEARANCE" if r.player_id == 4373
                else ("CONDITIONAL_ON_RELEASE_AND_FITNESS" if r.player_id == 8661
                else ("CONFIRMED_FREE_AGENT" if avail_st == "CONFIRMED_FREE_AGENT"
                else ("CONDITIONAL_ON_AUCTION_LIST_CONFIRMATION" if avail_st == "OFFICIALLY_RELEASED"
                else "CONDITIONAL_ON_RELEASE"))))
            ),
            "release_status": (
                "INTERNAL_RR_INCUMBENT" if ("INCUMBENT" in dec_cat or r.transaction_type == "INCUMBENT_RR_SQUAD")
                else ("PRE_2026_BCCI_DIRECTIVE_RELEASE" if r.player_id == 4373
                else ("CONTRACTED_RIVAL_INJURY_LIST" if r.player_id == 8661
                else ("OFFICIALLY_RELEASED" if avail_st == "OFFICIALLY_RELEASED"
                else ("PENDING_NOV17_RETENTION_LIST" if avail_st == "PENDING_NOV17_RETENTIONS"
                else "CONTRACTED_RIVAL_CORE"))))
            ),
            "decision_category": dec_cat,
            "notes": r.notes,
        })
    df = pd.DataFrame(rows)
    if output_dir is not None:
        out_path = Path(output_dir) / "ipl_availability_registry.csv"
        df.to_csv(out_path, index=False)
    return df


