def _compute_live_rr_ipl_hp_stats(out_dir: Optional[Path]) -> Dict[tuple, Dict[str, float]]:
    if out_dir is None:
        return {}
    ledger_path = Path(out_dir) / "delivery_impact_ledger.csv"
    if not ledger_path.exists():
        return {}
    usecols = [
        "comp_tier", "is_high_pressure_20", "is_reliability_eligible",
        "is_legal_ball", "striker_id", "bowler_id", "hp_bat_impact", "hp_bowl_impact",
    ]
    dlv = pd.read_csv(ledger_path, usecols=usecols)
    ipl_hp = dlv[dlv["comp_tier"].eq("IPL") & dlv["is_high_pressure_20"].astype(bool) & dlv["is_reliability_eligible"].astype(bool)]
    rr_pids = {d.primary_incumbent_id for d in RR_DEPTH_CHART} | {152, 50284, 6806, 7312, 4409}
    stats: Dict[tuple, Dict[str, float]] = {}
    for pid_col, imp_col, disc in [("striker_id", "hp_bat_impact", "batting"), ("bowler_id", "hp_bowl_impact", "bowling")]:
        sub = ipl_hp[ipl_hp[pid_col].isin(rr_pids)].groupby(pid_col).agg(
            balls=("is_legal_ball", "sum"),
            impact=(imp_col, "sum"),
        )
        for pid, r in sub.iterrows():
            b = int(r["balls"])
            rate = float((r["impact"] / b) * 12.0) if b > 0 else 0.0
            stats[(int(pid), disc)] = {"balls": b, "rate": round(rate, 2)}
    return stats


def build_rr_depth_chart(out_dir: Optional[Path] = None) -> pd.DataFrame:
    """Build the verified IPL 2026-27 RR playing XI depth chart with live ledger metrics when available."""
    live = _compute_live_rr_ipl_hp_stats(out_dir)
    rows = []
    for d in RR_DEPTH_CHART:
        m = live.get((d.primary_incumbent_id, d.discipline))
        balls = int(m["balls"]) if m else int(d.fallback_balls)
        rate = float(m["rate"]) if m else float(d.fallback_rate_12b)
        profile = f"{d.role_summary} (IPL HP: {rate:+.2f} runs/12b, {balls} legal balls)"
        rows.append({
            "tactical_role": d.tactical_role,
            "primary_incumbent_id": d.primary_incumbent_id,
            "primary_incumbent_name": d.primary_incumbent_name,
            "primary_profile": profile,
            "backup_player": d.backup_player_name or "None",
            "slot_type": d.slot_type,
            "pressure_workload_balls": balls,
            "incumbent_pressure_rate_12b": rate,
            "tactical_need_rating": d.tactical_need_rating,
        })
    return pd.DataFrame(rows)


